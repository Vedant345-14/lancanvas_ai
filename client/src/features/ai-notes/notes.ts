import type { Notes } from '../../types';

const list = (items: string[]) => items.filter(Boolean).map((s) => `- ${s}`).join('\n');
export function notesToMarkdown(n: Notes, imageRef?: string): string {
  const out: string[] = [`# ${n.title || 'Classroom notes'}`];
  if (n.overview) out.push('', n.overview);
  if (imageRef) out.push('', `![Whiteboard snapshot](${imageRef})`);
  const sec = (title: string, body: string) => { if (body.trim()) out.push('', `## ${title}`, '', body); };
  sec('Main concepts', n.mainConcepts.map((c) => `- **${c.name}**: ${c.explanation}`).join('\n'));
  sec('Important definitions', n.definitions.map((d) => `- **${d.term}**: ${d.definition}`).join('\n'));
  sec('Step-by-step explanations', n.steps.map((s, i) => `${i + 1}. **${s.title}**: ${s.detail}`).join('\n'));
  sec('Diagram explanations', n.diagramExplanations.map((d) => [`### ${d.title}`, d.observed && `**On the board:** ${d.observed}`, d.interpretation && `**AI interpretation:** ${d.interpretation}${d.uncertain ? ' _(uncertain: please verify)_' : ''}`].filter(Boolean).join('\n\n')).join('\n\n'));
  sec('Relationships between concepts', list(n.relationships));
  sec('Key terms, formulas and protocols', list(n.keyTerms));
  sec('Examples', list(n.examples));
  sec('Discussion points', list(n.discussionPoints));
  sec('Questions raised in chat', list(n.chatQuestions));
  sec('Revision notes', list(n.revisionNotes));
  sec('Practice questions', n.practiceQuestions.map((q, i) => `${i + 1}. ${q.question}${q.answer ? `\n   - **Answer:** ${q.answer}` : ''}`).join('\n'));
  sec('Flashcards', n.flashcards.map((f) => `- **${f.front}** → ${f.back}`).join('\n'));
  sec('Quick revision summary', n.quickSummary);
  sec('Things to double-check', list(n.caveats));
  return out.join('\n') + '\n';
}

export const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const inline = (s: string) => esc(s).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/(^|[\s(])_(.+?)_(?=[\s).,:;]|$)/g, '$1<em>$2</em>');

export function headings(md: string): { level: number; text: string; id: string }[] {
  return md.split('\n').map((l) => /^(#{2,3}) (.+)$/.exec(l)).filter(Boolean).map((m) => ({ level: m![1].length, text: m![2], id: slug(m![2]) }));
}

/** Tiny, safe Markdown subset -> HTML. All text is HTML-escaped first; images only allowed from data: URLs. */
export function mdToHtml(md: string, imageSrc?: string): string {
  const html: string[] = []; let inUl = false, inOl = false;
  const close = () => { if (inUl) html.push('</ul>'); if (inOl) html.push('</ol>'); inUl = inOl = false; };
  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    let m: RegExpExecArray | null;
    if (!line.trim()) { continue; }
    if ((m = /^(#{1,3}) (.+)$/.exec(line))) { close(); html.push(`<h${m[1].length} id="${slug(m[2])}">${inline(m[2])}</h${m[1].length}>`); }
    else if ((m = /^!\[(.*?)\]\((.*?)\)$/.exec(line))) { close(); if (imageSrc) html.push(`<figure><img src="${esc(imageSrc)}" alt="${esc(m[1])}"/><figcaption>${esc(m[1])}</figcaption></figure>`); }
    else if ((m = /^\s*- (.+)$/.exec(line))) { if (!inUl) { close(); html.push('<ul>'); inUl = true; } html.push(`<li>${inline(m[1])}</li>`); }
    else if ((m = /^\d+\. (.+)$/.exec(line))) { if (!inOl) { close(); html.push('<ol>'); inOl = true; } html.push(`<li>${inline(m[1])}</li>`); }
    else { close(); html.push(`<p>${inline(line)}</p>`); }
  }
  close(); return html.join('\n');
}

